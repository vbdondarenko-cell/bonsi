/**
 * Шаблони документів BONSI. Це робочі чернетки для адміністратора, а НЕ юридично перевірені тексти:
 * перед використанням у відносинах із клієнтом їх має переглянути юрист. Кожен шаблон це прямо зазначає.
 */
export type DocumentKind = "tech_spec" | "contract" | "amendment" | "stage_act" | "handover_act" | "access_handover" | "warranty_terms" | "other";

export const DOCUMENT_KINDS: DocumentKind[] = ["tech_spec", "contract", "amendment", "stage_act", "handover_act", "access_handover", "warranty_terms", "other"];

export type TemplateContext = {
  clientName: string;
  ticket: string;
  serviceTitle: string;
  price?: string | null;
  durationDays?: number | null;
  features?: string[];
  date: string;
};

const DISCLAIMER =
  "Увага: це шаблон-чернетка. Він не є юридично перевіреним документом, не замінює консультацію юриста й не створює зобов'язань, доки студія та клієнт не погодять остаточний текст.";

const list = (items: string[] | undefined, fallback: string) => (items && items.length ? items.map((item) => `- ${item}`).join("\n") : `- ${fallback}`);

export function renderTemplate(kind: DocumentKind, ctx: TemplateContext): { title: string; body: string } {
  const head = `Заявка ${ctx.ticket} · ${ctx.serviceTitle} · ${ctx.date}`;
  switch (kind) {
    case "tech_spec":
      return {
        title: `Технічне завдання ${ctx.ticket}`,
        body: [
          `# Технічне завдання`,
          head,
          `## 1. Мета проєкту\n[Опишіть, яку задачу клієнта розв'язує продукт]`,
          `## 2. Склад робіт\n${list(ctx.features, "[перелік функцій і сторінок]")}`,
          `## 3. Вимоги до дизайну й технологій\n- [платформи, браузери, пристрої]\n- [інтеграції]`,
          `## 4. Критерії приймання\n- [як клієнт перевірятиме результат]`,
          `## 5. Поза обсягом\n- Усе, що не перелічено в розділі 2, виконується лише після окремого погодження зміни.`,
          DISCLAIMER,
        ].join("\n\n"),
      };
    case "contract":
      return {
        title: `Договір на розробку ${ctx.ticket}`,
        body: [
          `# Договір на розробку`,
          head,
          `## 1. Сторони\n- Виконавець: BONSI Studios [реквізити виконавця]\n- Замовник: ${ctx.clientName} [реквізити замовника]`,
          `## 2. Предмет\nВиконавець розробляє продукт «${ctx.serviceTitle}» відповідно до погодженого технічного завдання та комерційної пропозиції.`,
          `## 3. Вартість і порядок оплати\n- Вартість: ${ctx.price ?? "[вказати]"}\n- Графік платежів: за погодженою комерційною пропозицією\n- Оплата вважається здійсненою після підтвердження надходження коштів Виконавцем`,
          `## 4. Строки\n- Орієнтовний строк: ${ctx.durationDays ? `${ctx.durationDays} дн.` : "[вказати]"} від активації проєкту`,
          `## 5. Зміни обсягу\nЗміни погоджуються окремою додатковою угодою з оцінкою вартості й строків. До погодження зміна не виконується.`,
          `## 6. Приймання\nЕтапи й результат приймаються за актами або погодженнями в кабінеті клієнта.`,
          `## 7. Гарантія і підтримка\n[умови гарантії та підтримки — за окремим документом]`,
          DISCLAIMER,
        ].join("\n\n"),
      };
    case "amendment":
      return { title: `Додаткова угода ${ctx.ticket}`, body: [`# Додаткова угода`, head, `## Предмет зміни\n[опис зміни]`, `## Вартість і строки\n- Додаткова вартість: [вказати]\n- Додатковий строк: [вказати]`, DISCLAIMER].join("\n\n") };
    case "stage_act":
      return { title: `Акт завершення етапу ${ctx.ticket}`, body: [`# Акт завершення етапу`, head, `## Етап\n[назва етапу]`, `## Що виконано\n- [перелік]`, `## Зауваження клієнта\n[за потреби]`, DISCLAIMER].join("\n\n") };
    case "handover_act":
      return {
        title: `Акт приймання-передачі ${ctx.ticket}`,
        body: [`# Акт приймання-передачі`, head, `## Передано\n${list(ctx.features, "[перелік переданих результатів]")}`, `## Підтвердження\nЗамовник підтверджує, що результат передано й перевірено відповідно до погодженого обсягу.`, DISCLAIMER].join("\n\n"),
      };
    case "access_handover":
      return {
        title: `Передача доступів ${ctx.ticket}`,
        body: [
          `# Передача доступів`,
          head,
          `## Що передається\n- [домен, хостинг, репозиторій, сторінки в магазинах застосунків — лише назви й місця]`,
          `## Правила безпеки\nПаролі, ключі та токени НЕ вказуються в цьому документі й не надсилаються в чаті. Їх передають окремим захищеним способом, погодженим сторонами.`,
          DISCLAIMER,
        ].join("\n\n"),
      };
    case "warranty_terms":
      return {
        title: `Умови гарантійної підтримки ${ctx.ticket}`,
        body: [
          `# Умови гарантійної підтримки`,
          head,
          `## Гарантійний період\n[тривалість визначає власник студії — у шаблоні навмисно не заповнено]`,
          `## Що входить у гарантію\n- Виправлення помилок, що виникли з вини Виконавця\n## Що виконується окремо за погодженням\n- Нові функції, зміни обсягу, зміни через зовнішні сервіси`,
          DISCLAIMER,
        ].join("\n\n"),
      };
    default:
      return { title: `Документ ${ctx.ticket}`, body: [`# Документ`, head, "[текст]", DISCLAIMER].join("\n\n") };
  }
}
